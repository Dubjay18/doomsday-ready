/**
 * Finds a YouTube trailer for every title in the catalogue and writes src/content/trailers.ts.
 * Run it once, review the printed titles/channels, and commit the result:  node scripts/fetch-trailers.mjs
 * Needs no API key: it reads YouTube's public search page, then checks each hit with oEmbed
 * (which also proves the video exists and allows embedding).
 *
 * Pass `--only id1,id2` to refresh specific titles, and `--q "custom query"` with a single --only id to override.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const catalogSrc = readFileSync(`${root}src/content/catalog.ts`, 'utf8')
const titles = [...catalogSrc.matchAll(/t\(\{ id: '([^']+)'(?:, phase: \d)?, name: '((?:[^'\\]|\\.)*)', kind: '(\w+)', year: (\d{4})/g)].map((m) => ({
  id: m[1],
  name: m[2].replace(/\\'/g, "'").replace(/’/g, "'"),
  kind: m[3],
  year: Number(m[4]),
}))

const args = process.argv.slice(2)
const only = args.includes('--only') ? args[args.indexOf('--only') + 1].split(',') : null
const customQ = args.includes('--q') ? args[args.indexOf('--q') + 1] : null

const outPath = `${root}src/content/trailers.ts`
const existing = {}
if (existsSync(outPath)) for (const m of readFileSync(outPath, 'utf8').matchAll(/'([^']+)': '([\w-]{11})'/g)) existing[m[1]] = m[2]

const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/120 Safari/537.36'
const GOOD_CHANNELS = /marvel|rotten tomatoes|movieclips|20th century|fox|sony|disney|warner|ign|joblo|movie trailers|fandango|ign|20th/i

async function search(q) {
  const res = await fetch(`https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`, { headers: { 'user-agent': UA, 'accept-language': 'en-US' } })
  const html = await res.text()
  return [...new Set([...html.matchAll(/"videoId":"([\w-]{11})"/g)].map((m) => m[1]))].slice(0, 6)
}

async function oembed(id) {
  const res = await fetch(`https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${id}&format=json`)
  if (!res.ok) return null
  return res.json()
}

const strip = (s) => s.toLowerCase().replace(/[^a-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim()

const result = { ...existing }
for (const t of titles) {
  if (only && !only.includes(t.id)) continue
  const base = t.name.replace(/\s*\(Season \d+\)/, '')
  const season = t.name.match(/\(Season (\d+)\)/)?.[1]
  const q = customQ ?? `${base} ${season ? `season ${season} ` : ''}${t.year} official trailer`
  let pick = null
  try {
    const ids = await search(q)
    const want = strip(base).split(' ').filter((w) => w.length > 2)
    for (const id of ids) {
      const o = await oembed(id)
      if (!o) continue
      const title = strip(o.title)
      const hits = want.filter((w) => title.includes(w)).length
      const isTrailer = /trailer|teaser|official/.test(title)
      const reaction = /react|review|breakdown|explained|fan|concept|ending|scene|clip|recap|every|ranking/.test(title)
      const score = hits / Math.max(want.length, 1) + (isTrailer ? 0.5 : 0) + (GOOD_CHANNELS.test(o.author_name) ? 0.5 : 0) - (reaction ? 1 : 0)
      if (!pick || score > pick.score) pick = { id, score, title: o.title, author: o.author_name }
    }
  } catch (e) {
    console.error('ERR', t.id, e.message)
  }
  if (pick) {
    result[t.id] = pick.id
    console.log(`${t.id.padEnd(46)} ${pick.id}  ${pick.score.toFixed(2)}  ${pick.title}  [${pick.author}]`)
  } else console.log(`${t.id.padEnd(46)} NONE`)
  await new Promise((r) => setTimeout(r, 400))
}

const lines = Object.entries(result).map(([k, v]) => `  '${k}': '${v}',`).join('\n')
writeFileSync(
  outPath,
  `/**
 * YouTube trailer IDs, keyed by catalogue id (plus 'doomsday' for the film itself).
 * Generated by scripts/fetch-trailers.mjs and reviewed by hand. Edit freely; re-run with --only <id> to refresh one.
 */
export const TRAILERS: Record<string, string> = {
${lines}
}
`,
)
